function wasAdded = add_functional_mission_supervisor(model,goalXY,sourceFile)
%ADD_FUNCTIONAL_MISSION_SUPERVISOR Monitor goal/collision/battery terminal.
% Idempotent top-level augmentation; does not change 7 Model References.
% Caller is responsible for saving the model and backing it up if needed.
assert(bdIsLoaded(model),'UAV:ModelNotLoaded', ...
    'Load top-level Simulink model before adding mission supervisor.');
assert(isfile(sourceFile),'UAV:MissingMissionSource', ...
    'Mission source file not found: %s',sourceFile);
assert(numel(goalXY)==2 && all(isfinite(goalXY)), ...
    'UAV:GoalInvalid','Mission goal must be finite [x;y].');
monitor = [model '/Mission Supervisor'];
if getSimulinkBlockHandle(monitor) ~= -1
    wasAdded = false;
    return;
end
assert(getSimulinkBlockHandle([model '/Dynamics'])~=-1 && ...
    getSimulinkBlockHandle([model '/Obstacle Map'])~=-1, ...
    'UAV:TopologyMismatch', ...
    'Existing Model Reference topology is not compatible.');

add_block('simulink/User-Defined Functions/MATLAB Function',monitor, ...
    'Position',[1510 80 1685 150]);
chart = find(sfroot,'-isa','Stateflow.EMChart','Path',monitor);
assert(~isempty(chart),'UAV:MissingMissionChart', ...
    'Could not locate Mission Supervisor MATLAB Function block.');
chart.Script = fileread(sourceFile);
chart.SupportVariableSizing = false;
add_block('simulink/Sources/Constant',[model '/Mission Goal'], ...
    'Value',mat2str(goalXY(:),12), ...
    'Position',[1280 55 1450 90]);
add_block('simulink/Sinks/Stop Simulation',[model '/Stop On Terminal State'], ...
    'Position',[1760 70 1815 110]);
add_block('simulink/Sinks/To Workspace',[model '/Mission Status Log'], ...
    'VariableName','uavf_mission_status', ...
    'SaveFormat','Timeseries','Position',[1760 140 1930 175]);
add_line(model,'Dynamics/1','Mission Supervisor/1','autorouting','on');
add_line(model,'Mission Goal/1','Mission Supervisor/2','autorouting','on');
add_line(model,'Obstacle Map/1','Mission Supervisor/3','autorouting','on');
add_line(model,'Mission Supervisor/1','Stop On Terminal State/1', ...
    'autorouting','on');
add_line(model,'Mission Supervisor/2','Mission Status Log/1', ...
    'autorouting','on');
wasAdded = true;
end
