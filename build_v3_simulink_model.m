function filename = build_v3_simulink_model()
%BUILD_V3_SIMULINK_MODEL Build independent nine-reference teaching V3 model.
% Seven person-owned MATLAB Function models + common Dynamics + Supervisor.
% V3 is codegen-friendly and autonomously changes its waypoint on detection.
% This model is distinct from Advanced MATLAB V2 and legacy UAVF_Team_Model.
% Existing .slx files are NEVER overwritten.
root = fileparts(mfilename('fullpath'));
setup_paths();
assert(license('test','Simulink')==1,'UAV3:NoLicense', ...
    'Simulink license is needed for this demonstrator.');
outDir = fullfile(root,'models','v3','generated');
if ~exist(outDir,'dir'), mkdir(outDir); end
addpath(outDir);

dt=0.1;
models={ ...
    'UAV3_Navigation_01', {'State','GPSValid'}, {'Navigation'}, ...
        fullfile(root,'team','01_Карпухин_Эрнест','v3_navigation.m'), ...
        {'[5 1]','1'}; ...
    'UAV3_Control_02', {'Navigation','Target'}, {'Command'}, ...
        fullfile(root,'team','02_Живоглядов_Иван','v3_control.m'), ...
        {'[4 1]','[2 1]'}; ...
    'UAV3_Replanner_03', {'Navigation','Observations','Goal'}, ...
        {'Target','PlanStatus'}, ...
        fullfile(root,'team','03_Лемченко_Богдан','v3_replanner.m'), ...
        {'[4 1]','[4 2]','[2 1]'}; ...
    'UAV3_Detection_04', {'Navigation','World'}, ...
        {'Observations','Nearest'}, ...
        fullfile(root,'team','04_Дзедзей_Александр','v3_detection.m'), ...
        {'[4 1]','[3 2]'}; ...
    'UAV3_GroundStation_05', ...
        {'Navigation','Energy','Nearest','SafetyCode','PlanStatus','GPSValid'}, ...
        {'Telemetry'}, ...
        fullfile(root,'team','05_Терехов_Арсений','v3_ground.m'), ...
        {'[4 1]','[3 1]','[4 1]','1','[3 1]','1'}; ...
    'UAV3_Safety_06', {'Command','Navigation','Nearest','Energy'}, ...
        {'SafeControl','SafetyCode'}, ...
        fullfile(root,'team','06_Пучков_Артём','v3_safety.m'), ...
        {'[2 1]','[4 1]','[4 1]','[3 1]'}; ...
    'UAV3_Energy_07', {'State','Command'}, {'Energy'}, ...
        fullfile(root,'team','07_Касимов_Иван','v3_energy.m'), ...
        {'[5 1]','[2 1]'}; ...
    'UAV3_Dynamics', {'SafeControl','Energy'}, {'State'}, ...
        fullfile(root,'models','functional','dynamics_step.m'), ...
        {'[2 1]','[3 1]'}; ...
    'UAV3_MissionLifecycle', {'State','Goal','World'}, ...
        {'StopNow','MissionCode'}, ...
        fullfile(root,'models','functional','mission_supervisor.m'), ...
        {'[5 1]','[2 1]','[3 2]'} ...
    };

for k=1:size(models,1)
    v3_component_model(models{k,1},models{k,2},models{k,3}, ...
        models{k,4},models{k,5},outDir,dt,strcmp(models{k,1}, ...
        'UAV3_Dynamics'));
end

main='UAV3_Team_Model';
filename=fullfile(outDir,[main '.slx']);
if isfile(filename)
    load_system(filename);
    open_system(main);
    fprintf('Existing V3 model preserved (no overwrite): %s\n',filename);
    return;
end

new_system(main);
set_param(main,'Solver','FixedStepDiscrete','FixedStep',num2str(dt), ...
    'StopTime','90','ReturnWorkspaceOutputs','on');

% Fixed-size synthetic world: 2 slots, one obstacle initially relevant.
% The sensor does NOT share this map with the planner until object in range.
v3_constant(main,'World Map','[50 1000;40 1000;7 0]','WORLD', ...
    [65 100 235 145]);
v3_constant(main,'Mission Goal','[100;80]','GOAL', ...
    [65 195 235 240]);

% Clock supplies the satellite-loss scenario and is not a seventh subsystem.
add_block('simulink/Sources/Clock',[main '/Simulation Time'], ...
    'Position',[60 300 120 335]);
gpsBlock=[main '/GPS Outage Generator'];
add_block('simulink/User-Defined Functions/MATLAB Function',gpsBlock, ...
    'Position',[155 295 305 355]);
chart=find(sfroot,'-isa','Stateflow.EMChart','Path',gpsBlock);
assert(~isempty(chart),'UAV3:NoGPSChart','Cannot create GPS chart.');
chart.Script=fileread(fullfile(root,'models','v3','v3_gps_schedule.m'));
add_line(main,'Simulation Time/1','GPS Outage Generator/1', ...
    'autorouting','on');
v3_signal_source(main,'GPS Outage Generator/1','GPS_VALID', ...
    [330 302 405 326]);

% Visual separation of detection, planning, motion and monitoring:
% References are linked through named global signals, not long crossings.
v3_reference(main,'01 Navigation',models{1,1}, ...
    {'FEEDBACK_STATE','GPS_VALID'},{'NAV'},[245 440 465 530], ...
    'lightBlue');
v3_reference(main,'04 Detection',models{4,1}, ...
    {'NAV','WORLD'},{'OBS','NEAREST'},[690 430 915 525], ...
    'cyan');
v3_reference(main,'03 Online Replanning',models{3,1}, ...
    {'NAV','OBS','GOAL'},{'TARGET','PLAN_INFO'},[1120 405 1360 530], ...
    'orange');
v3_reference(main,'02 Flight Control',models{2,1}, ...
    {'NAV','TARGET'},{'COMMAND'},[1580 425 1800 525], ...
    'lightBlue');
v3_reference(main,'06 Safety Supervisor',models{6,1}, ...
    {'COMMAND','NAV','NEAREST','ENERGY'}, ...
    {'SAFE','SAFETY_CODE'},[2020 410 2260 550], 'yellow');

v3_reference(main,'07 Battery and Energy',models{7,1}, ...
    {'FEEDBACK_STATE','COMMAND'},{'ENERGY'}, ...
    [710 760 945 850],'green');
v3_reference(main,'05 Ground Station',models{5,1}, ...
    {'NAV','ENERGY','NEAREST','SAFETY_CODE','PLAN_INFO','GPS_VALID'}, ...
    {'TELEMETRY'},[1120 725 1380 905],'gray');
v3_reference(main,'Common Dynamics',models{8,1}, ...
    {'SAFE','ENERGY'},{'STATE'},[1590 755 1810 865], ...
    'lightBlue');
v3_reference(main,'Mission Lifecycle',models{9,1}, ...
    {'STATE','GOAL','WORLD'},{'STOP_NOW','MISSION_CODE'}, ...
    [2020 760 2260 870],'orange');

% Explicit state feedback delay at the top level prevents algebraic loops.
v3_signal_receiver(main,'STATE','State feedback source', ...
    [2410 740 2500 765]);
add_block('simulink/Discrete/Unit Delay', ...
    [main '/Feedback Delay'], ...
    'InitialCondition','[0;0;0;0;100]', ...
    'SampleTime',num2str(dt), ...
    'Position',[2540 736 2590 775]);
add_line(main,'State feedback source/1','Feedback Delay/1', ...
    'autorouting','on');
v3_signal_source(main,'Feedback Delay/1','FEEDBACK_STATE', ...
    [2620 739 2710 766]);

v3_logger(main,'STATE','State Log','uav3_state',[2390 920 2580 950]);
v3_logger(main,'TELEMETRY','Telemetry Log','uav3_telemetry', ...
    [1150 955 1360 985]);
v3_logger(main,'PLAN_INFO','Plan Events Log','uav3_plan', ...
    [1420 955 1630 985]);
v3_logger(main,'MISSION_CODE','Mission Code Log','uav3_mission', ...
    [2060 955 2260 985]);
v3_signal_receiver(main,'STOP_NOW','Terminal State', ...
    [2400 845 2510 870]);
add_block('simulink/Sinks/Stop Simulation',[main '/Stop on Mission End'], ...
    'Position',[2560 833 2610 885]);
add_line(main,'Terminal State/1','Stop on Mission End/1', ...
    'autorouting','on');

title=Simulink.Annotation(main, ...
    'UAV V3 | SEVEN INDEPENDENT MODELS + SHARED DYNAMICS / SUPERVISOR');
title.Position=[75 18 1560 65];
title.FontSize=17;
title.ForegroundColor='blue';
footer=Simulink.Annotation(main, ...
    'LIVE RANGE DETECTION -> WAYPOINT REPLAN -> CONTROL -> SAFETY -> 2D DYNAMICS');
footer.Position=[70 1020 1850 1055];
footer.FontSize=11;
footer.ForegroundColor='darkGreen';

save_system(main,filename);
open_system(main);
fprintf('Created V3 Model-Based Design demo: %s\n',filename);
fprintf('Seven owner components + shared Dynamics and Mission Lifecycle.\n');
fprintf('V3 is a 2D student simulation; verify with run_v3_simulink_demo.\n');
end

function v3_component_model(name,inputs,outputs,sourceFile,portSizes, ...
    outDir,dt,isDynamics)
file=fullfile(outDir,[name '.slx']);
if isfile(file)
    load_system(file);
    fprintf('Existing V3 component preserved: %s\n',name);
    return;
end
assert(isfile(sourceFile),'UAV3:SourceMissing', ...
    'Missing source: %s',sourceFile);
new_system(name);
set_param(name,'Solver','FixedStepDiscrete', ...
    'FixedStep',num2str(dt));
for k=1:numel(inputs)
    add_block('simulink/Sources/In1',[name '/' inputs{k}], ...
        'Port',num2str(k),'PortDimensions',portSizes{k}, ...
        'OutDataTypeStr','double', ...
        'Position',[45 50+64*(k-1) 105 70+64*(k-1)]);
end
for k=1:numel(outputs)
    add_block('simulink/Sinks/Out1',[name '/' outputs{k}], ...
        'Port',num2str(k), ...
        'Position',[510 60+65*(k-1) 575 80+65*(k-1)]);
end
logic=[name '/Algorithm'];
add_block('simulink/User-Defined Functions/MATLAB Function',logic, ...
    'Position',[245 90 405 180]);
chart=find(sfroot,'-isa','Stateflow.EMChart','Path',logic);
assert(~isempty(chart),'UAV3:NoChart','No MATLAB Function block.');
chart.Script=fileread(sourceFile);
chart.SupportVariableSizing=false;
if isDynamics
    memory=[name '/Dynamics Memory'];
    add_block('simulink/Discrete/Unit Delay',memory, ...
        'InitialCondition','[0;0;0;0;100]', ...
        'SampleTime',num2str(dt), ...
        'Position',[425 255 465 295]);
    add_line(name,'Dynamics Memory/1','State/1','autorouting','on');
    add_line(name,'Dynamics Memory/1','Algorithm/1','autorouting','on');
    add_line(name,'SafeControl/1','Algorithm/2','autorouting','on');
    add_line(name,'Energy/1','Algorithm/3','autorouting','on');
    add_line(name,'Algorithm/1','Dynamics Memory/1','autorouting','on');
else
    for k=1:numel(inputs)
        add_line(name,sprintf('%s/1',inputs{k}), ...
            sprintf('Algorithm/%d',k),'autorouting','on');
    end
    for k=1:numel(outputs)
        add_line(name,sprintf('Algorithm/%d',k), ...
            sprintf('%s/1',outputs{k}),'autorouting','on');
    end
end
save_system(name,file);
fprintf('Created V3 executable component: %s\n',name);
end

function v3_reference(main,label,refName,inTags,outTags,p,color)
path=[main '/' label];
add_block('simulink/Ports & Subsystems/Model',path, ...
    'ModelName',refName,'Position',p,'BackgroundColor',color);
for k=1:numel(inTags)
    tag=inTags{k};
    fromName=sprintf('%s input %d',label,k);
    yy=p(2)+20+29*(k-1);
    v3_signal_receiver(main,tag,fromName, ...
        [p(1)-145 yy-10 p(1)-45 yy+10]);
    add_line(main,[fromName '/1'],sprintf('%s/%d',label,k), ...
        'autorouting','on');
end
for k=1:numel(outTags)
    tag=outTags{k};
    gotoName=sprintf('%s output %d',label,k);
    yy=p(2)+21+29*(k-1);
    block=[main '/' gotoName];
    add_block('simulink/Signal Routing/Goto',block, ...
        'GotoTag',tag,'TagVisibility','global', ...
        'Position',[p(3)+37 yy-10 p(3)+136 yy+10]);
    add_line(main,sprintf('%s/%d',label,k),[gotoName '/1'], ...
        'autorouting','on');
end
end

function v3_constant(main,label,value,tag,p)
add_block('simulink/Sources/Constant',[main '/' label], ...
    'Value',value,'Position',p);
v3_signal_source(main,[label '/1'],tag, ...
    [p(3)+20 p(2)+8 p(3)+126 p(2)+32]);
end

function v3_signal_source(main,src,tag,p)
name=[main '/Tag ' tag];
add_block('simulink/Signal Routing/Goto',name, ...
    'GotoTag',tag,'TagVisibility','global','Position',p);
add_line(main,src,['Tag ' tag '/1'],'autorouting','on');
end

function v3_signal_receiver(main,tag,name,p)
add_block('simulink/Signal Routing/From',[main '/' name], ...
    'GotoTag',tag,'Position',p);
end

function v3_logger(main,tag,label,variable,p)
from=[label ' input'];
v3_signal_receiver(main,tag,from,[p(1)-115 p(2) p(1)-15 p(2)+20]);
add_block('simulink/Sinks/To Workspace',[main '/' label], ...
    'VariableName',variable,'SaveFormat','Timeseries', ...
    'Position',p);
add_line(main,[from '/1'],[label '/1'],'autorouting','on');
end
